"""Paths and constants.

Modules read these at call time (``cfg.STATS_CSV``), so tests can redirect
everything to a temp folder with :func:`configure`.
"""
import os
from pathlib import Path

try:  # optional: load FOOTBALL_DATA_TOKEN from a local, git-ignored .env file
    from dotenv import load_dotenv

    load_dotenv(Path(__file__).resolve().parent.parent / ".env")
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = Path(os.environ.get("PLVALUE_DATA", ROOT / "data"))
RAW_DIR = DATA_DIR / "raw"              # Kaggle Transfermarkt files go here
PROCESSED_DIR = DATA_DIR / "processed"  # generated by `fetch` and `build`
MODELS_DIR = ROOT / "models"
REPORTS_DIR = ROOT / "reports"

STATS_CSV = PROCESSED_DIR / "stats.csv"
VALUES_CSV = PROCESSED_DIR / "values.csv"
TM_FEATURES_CSV = PROCESSED_DIR / "tm_features.csv"
MODEL_PATH = MODELS_DIR / "model.joblib"

API_BASE = "https://api.football-data.org/v4"
# key -> (competition code, season start year, column prefix)
SOURCES = {
    "last": ("PL", 2025, "l"),   # 2025/26, last completed season
    "cur": ("PL", 2026, "c"),    # 2026/27, in progress
    "wc": ("WC", 2026, "wc"),    # World Cup 2026
}
SEASON_START, SEASON_END = "2025-07-01", "2026-06-30"
SEED = 42


def get_token() -> str:
    return os.environ.get("FOOTBALL_DATA_TOKEN", "")


def configure(data_dir=None, models_dir=None, reports_dir=None):
    """Redirect input/output folders (used by the tests)."""
    global DATA_DIR, RAW_DIR, PROCESSED_DIR, MODELS_DIR, REPORTS_DIR
    global STATS_CSV, VALUES_CSV, TM_FEATURES_CSV, MODEL_PATH
    if data_dir is not None:
        DATA_DIR = Path(data_dir)
        RAW_DIR, PROCESSED_DIR = DATA_DIR / "raw", DATA_DIR / "processed"
        STATS_CSV = PROCESSED_DIR / "stats.csv"
        VALUES_CSV = PROCESSED_DIR / "values.csv"
        TM_FEATURES_CSV = PROCESSED_DIR / "tm_features.csv"
    if models_dir is not None:
        MODELS_DIR = Path(models_dir)
        MODEL_PATH = MODELS_DIR / "model.joblib"
    if reports_dir is not None:
        REPORTS_DIR = Path(reports_dir)
